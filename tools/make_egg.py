#!/usr/bin/env python3
"""Writes packaging/rift/pterodactyl-egg.json from packaging/rift/install.sh.

The egg embeds the install script, so the script is the one to edit; run this to update the egg, and
`--check` to see that the committed egg is up to date (it exits 1 when it is not).
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
INSTALL = ROOT / "packaging" / "rift" / "install.sh"
EGG = ROOT / "packaging" / "rift" / "pterodactyl-egg.json"


def variable(name, env, description, default, rules, editable=True):
    return {
        "name": name,
        "description": description,
        "env_variable": env,
        "default_value": default,
        "user_viewable": True,
        "user_editable": editable,
        "rules": rules,
        "field_type": "text",
    }


def egg():
    return {
        "_comment": "Generated by tools/make_egg.py from packaging/rift/install.sh: edit that and run it.",
        "meta": {"version": "PTDL_v2", "update_url": None},
        "exported_at": "2026-11-15T00:00:00+00:00",
        "name": "Rift Event Server",
        # The panel validates the author as an email address and fails the import (a 500) when it is not one.
        "author": "rift-event-server@example.com",
        "description": (
            "Rift Event Server: a Minecraft 26.3 server written in Rust. Installs the Linux x86-64 build from "
            "the GitHub release named by RIFT_VERSION. The prepared game files (made from your own Minecraft "
            "copy with rift-prepare) are uploaded to resources/ by hand."
        ),
        "features": None,
        "docker_images": {"Debian": "ghcr.io/ptero-eggs/yolks:debian"},
        "file_denylist": [],
        "startup": "sh ./start.sh",
        "config": {
            "files": "{}",
            "startup": json.dumps({"done": 'For help, type "help"'}),
            "logs": "{}",
            "stop": "stop",
        },
        "scripts": {
            "installation": {
                "script": INSTALL.read_text(),
                "container": "debian:bookworm-slim",
                "entrypoint": "bash",
            }
        },
        "variables": [
            variable(
                "Rift release",
                "RIFT_VERSION",
                "The release to install: nightly (every push to dev) or a tag. Read at install and reinstall.",
                "nightly",
                "required|string|max:64",
            ),
            variable(
                "EULA",
                "HORIZON_EULA",
                "true accepts the Minecraft EULA (https://aka.ms/MinecraftEULA). Until then the server stops "
                "at start and says why. Read on the first start.",
                "false",
                "required|string|in:true,false",
            ),
            variable(
                "Online mode",
                "HORIZON_ONLINE",
                "false behind a Velocity proxy that signs players in (put the proxy's forwarding.secret in the "
                "server folder). true checks players' Minecraft accounts here. Read on the first start.",
                "true",
                "required|string|in:true,false",
            ),
            variable(
                "Whitelist",
                "HORIZON_WHITELIST",
                "true: only whitelisted players and operators can join. Read on the first start.",
                "true",
                "required|string|in:true,false",
            ),
            variable(
                "Players",
                "HORIZON_PLAYERS",
                "Names to whitelist, separated by commas. Read on the first start.",
                "",
                "nullable|string|max:512",
            ),
            variable(
                "Operator",
                "HORIZON_OP",
                "A name to make an operator. Read on the first start.",
                "",
                "nullable|string|max:16",
            ),
            variable(
                "World",
                "HORIZON_WORLD",
                "The world folder's name. Read on the first start.",
                "world",
                "required|string|max:64",
            ),
            variable(
                "Seed",
                "HORIZON_SEED",
                "The world seed; empty is a random one. Read on the first start.",
                "",
                "nullable|string|max:64",
            ),
        ],
    }


def main():
    text = json.dumps(egg(), indent=2) + "\n"
    if "--check" in sys.argv[1:]:
        if not EGG.exists() or EGG.read_text() != text:
            print(f"{EGG.relative_to(ROOT)} is out of date: run tools/make_egg.py")
            sys.exit(1)
        return
    EGG.write_text(text)
    print(f"Wrote {EGG.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
